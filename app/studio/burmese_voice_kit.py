"""Burmese Voice Kit preprocessing, adapted from edotheDev/burmese-voice-kit (MIT).

This is a lightweight local preparation layer, not a TTS engine. Voice audio is
still generated by the configured ElevenLabs account; Edge TTS remains free
and unchanged. Only enable this layer for Burmese ElevenLabs narration.
"""
from __future__ import annotations

import re
import unicodedata
from pathlib import Path

DIGITS = ["သုည", "တစ်", "နှစ်", "သုံး", "လေး", "ငါး", "ခြောက်", "ခုနစ်", "ရှစ်", "ကိုး"]
PCT_WORD = "ရာခိုင်နှုန်း"
MAX_N = 9_999_999
MY_TO_LATIN = {ord(c): str(i) for i, c in enumerate("၀၁၂၃၄၅၆၇၈၉")}
_NUM_RE = re.compile(
    r"(?<![A-Za-z0-9၀-၉])"
    r"(?P<num>[0-9၀-၉]+(?:,[0-9၀-၉]{3})*(?:\.[0-9၀-၉]+)?)"
    r"(?P<pct>\s*%)?"
    r"(?![A-Za-z0-9၀-၉])"
)
_GLUED_RE = re.compile(r"[A-Za-z][0-9၀-၉]+|[0-9၀-၉]+[A-Za-z]")


def to_words(number: int) -> str:
    """Convert an integer from 0 to 9,999,999 into spoken Burmese."""
    if not isinstance(number, int) or number < 0 or number > MAX_N:
        raise ValueError("only integers 0 to 9,999,999 are supported")
    if number == 0:
        return DIGITS[0]
    places = [
        (1_000_000, "သန်း", "သန်း", None),
        (100_000, "သိန်း", "သိန်း", None),
        (10_000, "သောင်း", "သောင်း", None),
        (1_000, "ထောင်", "ထောင့်", 1_000),
        (100, "ရာ", "ရာ့", 100),
        (10, "ဆယ်", "ဆယ့်", 10),
    ]
    out, rest = [], number
    for divisor, plain, creaky, modulus in places:
        digit = rest // divisor
        rest %= divisor
        if not digit:
            continue
        word = creaky if modulus is not None and number % modulus else plain
        if divisor == 10 and digit == 1 and 11 <= number <= 19:
            out.append(word)
        else:
            out.append(DIGITS[digit] + word)
    if rest:
        out.append(DIGITS[rest])
    return "".join(out)


def replace_numbers(text: str) -> tuple[str, list[str]]:
    """Convert supported integers; leave decimals/large/ambiguous values flagged."""
    flags: list[str] = []

    def replace(match: re.Match[str]) -> str:
        raw, percent = match.group("num"), match.group("pct")
        latin = raw.translate(MY_TO_LATIN)
        if "." in latin:
            flags.append(f"decimal left as is: {raw}")
            return match.group(0)
        digits = latin.replace(",", "")
        if len(digits) > 1 and digits.startswith("0"):
            flags.append(f"leading zero left as is: {raw}")
            return match.group(0)
        number = int(digits)
        if number > MAX_N:
            flags.append(f"too big, write by hand: {raw}")
            return match.group(0)
        return to_words(number) + (" " + PCT_WORD if percent else "")

    prepared = _NUM_RE.sub(replace, str(text or ""))
    flags.extend(f"digits glued to letters left as is: {item}" for item in _GLUED_RE.findall(prepared))
    return prepared, flags


def load_lexicon(path: str | Path | None = None) -> list[tuple[str, str]]:
    """Read the bundled written<TAB>spoken lexicon, longest entries first."""
    source = Path(path) if path else Path(__file__).resolve().parents[2] / "data" / "burmese_voice_kit" / "lexicon.tsv"
    if not source.is_file():
        return []
    rows: list[tuple[str, str]] = []
    for line in source.read_text(encoding="utf-8-sig").splitlines():
        if not line.strip() or line.lstrip().startswith("#") or "\t" not in line:
            continue
        written, spoken = line.split("\t", 1)
        if written.strip() and spoken.strip():
            rows.append((written.strip(), spoken.strip()))
    return sorted(rows, key=lambda pair: len(pair[0]), reverse=True)


def prepare_burmese_text(text: str, lexicon_path: str | Path | None = None) -> tuple[str, list[str]]:
    """Normalize, apply verified pronunciation substitutions, and convert numbers."""
    value = unicodedata.normalize("NFC", str(text or ""))
    for written, spoken in load_lexicon(lexicon_path):
        value = value.replace(written, spoken)
    value, flags = replace_numbers(value)
    return re.sub(r"\s+", " ", value).strip(), flags
